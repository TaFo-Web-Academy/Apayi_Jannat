export function calculateTestResult(
  answers: Record<number, OptionLetter>,
  testConfig: TestConfig = DEFAULT_TEST
): {
  answerCode: string;
  scores: CalculatedStateScore[];
  dominantState: CalculatedStateScore;
  vulnerablePercentage: number;
  resourcefulPercentage: number;
  difficultSpheres: DifficultSphereItem[];
  strongSpheres: DifficultSphereItem[];
} {
  const totalQuestions = testConfig.questions.length || 10;
  const counts: Record<OptionLetter, number> = {
    А: 0,
    Б: 0,
    В: 0,
    Г: 0,
    Д: 0,
    Е: 0,
    Ж: 0,
    З: 0
  };

  const difficultSpheres: DifficultSphereItem[] = [];
  const strongSpheres: DifficultSphereItem[] = [];

  const codeParts: string[] = [];

  for (const q of testConfig.questions) {
    const chosen = answers[q.id];
    if (chosen && counts[chosen] !== undefined) {
      counts[chosen] += 1;
      codeParts.push(`${q.id}-${chosen}`);
      const stateInfo = EMOTIONAL_STATES[chosen];
      const optObj = q.options.find((o) => o.letter === chosen);
      const item: DifficultSphereItem = {
        questionId: q.id,
        sphere: q.sphere,
        letter: chosen,
        stateName: stateInfo.fullName,
        answerText: optObj ? optObj.text : ""
      };
      if (stateInfo.category === "vulnerable") {
        difficultSpheres.push(item);
      } else {
        strongSpheres.push(item);
      }
    }
  }

  const scores: CalculatedStateScore[] = ORDERED_LETTERS.map((letter) => {
    const info = EMOTIONAL_STATES[letter];
    const count = counts[letter];
    const percentage = Math.round((count / totalQuestions) * 100);
    return {
      letter,
      shortName: info.shortName,
      fullName: info.fullName,
      category: info.category,
      count,
      percentage
    };
  });

  // Dominant state (highest count; tie-breaker favors first occurrence)
  let dominantState = scores[0];
  for (const s of scores) {
    if (s.count > dominantState.count) {
      dominantState = s;
    }
  }

  const vulnerablePercentage = scores
    .filter((s) => s.category === "vulnerable")
    .reduce((acc, s) => acc + s.percentage, 0);

  const resourcefulPercentage = scores
    .filter((s) => s.category === "resourceful")
    .reduce((acc, s) => acc + s.percentage, 0);

  return {
    answerCode: codeParts.join(", "),
    scores,
    dominantState,
    vulnerablePercentage,
    resourcefulPercentage,
    difficultSpheres,
    strongSpheres
  };
}
