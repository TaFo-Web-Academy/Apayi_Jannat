export type OptionLetter = "А" | "Б" | "В" | "Г" | "Д" | "Е" | "Ж" | "З";

export interface EmotionalStateInfo {
  letter: OptionLetter;
  shortName: string; // As shown in "Харитаи эҳсосоти шумо" (e.g. Ноумедӣ, Гунаҳкорӣ...)
  fullName: string;  // Full table title (e.g. Ноумедӣ ва беарзишӣ)
  category: "vulnerable" | "resourceful";
  color: string;     // Bar color hex
  summary: string;   // Psychological explanation in Tajik
  exercises: string[]; // 5 practical exercises in Tajik
}

export interface TestOption {
  letter: OptionLetter;
  text: string;
}

export interface TestQuestion {
  id: number;
  sphere: string;
  question: string;
  options: TestOption[];
}

export interface TestConfig {
  id: string;
  slug: string;
  title: string;
  subtitle: string;
  author: string;
  badgeText: string;
  description: string;
  instruction: string;
  disclaimer: string;
  questions: TestQuestion[];
}

export interface CalculatedStateScore {
  letter: OptionLetter;
  shortName: string;
  fullName: string;
  category: "vulnerable" | "resourceful";
  count: number;
  percentage: number;
}

export interface DifficultSphereItem {
  questionId: number;
  sphere: string;
  letter: OptionLetter;
  stateName: string;
  answerText: string;
}

export interface SubmissionRecord {
  id: string;
  createdAt: string;
  respondentName: string;
  respondentAge?: string;
  respondentGender?: string;
  respondentPhone?: string;
  respondentNote?: string;
  answers: Record<number, OptionLetter>; // questionId -> letter
  answerCode: string; // "1-Д, 2-Ж, 3-В..."
  scores: CalculatedStateScore[];
  dominantState: CalculatedStateScore;
  vulnerablePercentage: number;
  resourcefulPercentage: number;
  difficultSpheres: DifficultSphereItem[];
  strongSpheres: DifficultSphereItem[];
}

